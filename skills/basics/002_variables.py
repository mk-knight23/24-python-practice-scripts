#!/usr/bin/env python3
"""
Purpose: Learn variables - named boxes that hold data.

Input: None
Output: Shows different data types in action

Example:
    $ python 002_variables.py
    Name: Alice
    Age: 25
    Temperature: 98.6
    Is student: True

Why: Variables are memory. Without them, your program forgets 
     everything immediately. With them, you can build complexity.
"""

# --- your code below ---

# String - text data
name = "Alice"

# Integer - whole numbers
age = 25

# Float - decimal numbers
temperature = 98.6

# Boolean - True or False
is_student = True

# Print them all
print("Name:", name)
print("Age:", age)
print("Temperature:", temperature)
print("Is student:", is_student)

# --- try this ---
# Create a variable for your own name and print it
your_name = "your name here"
print("My name is:", your_name)
